export const ALL_VERIFIED = UNVERIFIED_COUNT === 0;

export const CARD_IDS: string[] = CARDS.map((c) => c.id);

const CARD_BY_ID = new Map(CARDS.map((c) => [c.id, c]));

export function getCard(id: string): Card | undefined {
  return CARD_BY_ID.get(id);
}

export function cardsByGenre(genre: Genre): Card[] {
  return CARDS.filter((c) => c.genre === genre);
}

/** QRの ?spot= から引くための逆引き表 */
const CARD_BY_SPOT = new Map(
  CARDS.filter((c) => c.spotId).map((c) => [c.spotId as string, c])
);

export function getCardBySpotId(spotId: string): Card | undefined {
  return CARD_BY_SPOT.get(spotId);
}

export const SPOT_IDS: string[] = CARDS.filter((c) => c.spotId).map(
  (c) => c.spotId as string
);
